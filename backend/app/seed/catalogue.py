def seed_catalogue(state: State, now: datetime) -> None:
    state.departments.update({i: Department(id=i, name=n, code=i.upper()) for i, n in DEPARTMENTS.items()})
    for key, name, department, room, opens, closes, days, supervisor in LABS:
        lab = Lab(
            id=f"lab-{key}",
            name=name,
            department_id=department,
            room=room,
            building=f"Block {room[0]}",
            opening_hours={i: [Window(open=opens, close=closes)] for i in range(days)},
            supervisor_ids=[supervisor] if supervisor else [],
        )
        state.labs[lab.id] = lab
    for key, name, lab_key, category, count, approval, training, tags, spec in INVENTORY:
        lab = state.labs[f"lab-{lab_key}"]
        first, first_value, second, second_value = spec.split("|")
        capabilities = tags.split(",")
        item = Equipment(
            id=f"eq-{key}",
            name=name,
            category=Category(category),
            lab_id=lab.id,
            department_id=lab.department_id,
            kind=category if category in ("dev_kit", "workstation") else "equipment",
            description=(
                f"Shared campus resource in the {lab.name}. Supports {', '.join(capabilities[:3]).replace('-', ' ')}."
            ),
            specs={first: first_value, second: second_value},
            capability_tags=capabilities,
            unit_ids=[f"eq-{key}-unit-{n + 1}" for n in range(count)],
            approval_mode="faculty" if approval else "auto",
            required_training=training,
            high_demand=key in {"prusa", "gpu-4090", "spectrum-keysight"},
            created_at=now,
            updated_at=now,
        )
        state.equipment[item.id] = item
